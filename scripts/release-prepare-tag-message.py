#!/usr/bin/env python3
"""Prepare a complete public tag message outside the repository, without clobber."""

import os
import re
import sys
from pathlib import Path

FOOTER = re.compile(
    r"(?:^|\n\n)"
    r"Role: [a-z][a-z0-9-]*\n"
    r"Co-[Aa]uthored-[Bb]y: .+ <noreply@3leaps\.net>\n"
    r"Committer-of-Record: @3leapsdave\n$"
)
RETIRED_FOOTER = re.compile(r"(?:^|\n)Generated by .+ via .+ under supervision of @")
PLACEHOLDER = re.compile(
    r"<(?:[A-Z][A-Z -]*|model|interface[^<>]*|role|TODO[^<>]*|REPLACE[^<>]*)>",
    re.I,
)


def fail(reason: str) -> None:
    raise ValueError(reason)


def subject_for(tag: str) -> str:
    return f"Release {tag[1:]}" if tag.startswith("v") else tag


def validate_message(data: bytes, subject: str | None = None) -> str:
    try:
        message = data.decode("utf-8")
    except UnicodeError:
        fail("tag message must be UTF-8")
    if (
        not data
        or b"\x00" in data
        or b"\r" in data
        or not data.endswith(b"\n")
        or data.endswith(b"\n\n")
        or any(line.rstrip(b" \t") != line for line in data.splitlines())
    ):
        fail(
            "tag message needs one final newline and no CR, NUL or trailing whitespace"
        )
    if PLACEHOLDER.search(message):
        fail("tag message contains an unresolved placeholder")
    if RETIRED_FOOTER.search(message) or not FOOTER.search(message):
        fail("tag message must end with the complete attribution footer")
    if subject is not None and message.split("\n", 1)[0] != subject:
        fail(f"tag message subject must be {subject!r}")
    return message


def message_dir(root: Path, tag: str) -> Path:
    raw = os.environ.get("GONIMBUS_TAG_MESSAGE_DIR", "")
    directory = Path(raw)
    if (
        not raw
        or not directory.is_absolute()
        or ".." in directory.parts
        or directory.name != tag
    ):
        fail(
            "external absolute per-cut message directory ending in release tag required"
        )

    current = Path(directory.anchor)
    for part in directory.parts[1:]:
        current /= part
        if current.is_symlink():
            fail("message directory may not contain symlink ancestors")
    resolved = directory.resolve(strict=False)
    for candidate in (directory, resolved):
        for ancestor in (candidate, *candidate.parents):
            try:
                if ancestor.exists() and os.path.samefile(ancestor, root):
                    fail("message directory must be outside the repository")
            except OSError:
                continue
    if resolved == root or root in resolved.parents:
        fail("message directory must be outside the repository")
    if resolved.name != tag:
        fail("message directory must resolve to a directory named for the release tag")
    directory.mkdir(mode=0o700, parents=True, exist_ok=True)
    if directory.is_symlink() or not directory.is_dir():
        fail("message directory must be a real directory")
    return directory


def prepare() -> None:
    root = Path(__file__).resolve().parent.parent
    tag = os.environ.get("GONIMBUS_RELEASE_TAG", "")
    if tag != f"v{(root / 'VERSION').read_text().strip()}":
        fail("release tag must match VERSION")
    directory = message_dir(root, tag)

    file = directory / f"{tag.replace('/', '__')}.txt"
    skeleton = (
        f"{subject_for(tag)}\n\n"
        "<SUMMARY OF THE RELEASE>\n\n"
        "Role: <role>\n"
        "Co-authored-by: <model> <noreply@3leaps.net>\n"
        "Committer-of-Record: @3leapsdave\n"
    ).encode("utf-8")
    try:
        descriptor = os.open(
            file, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600
        )
    except FileExistsError:
        state = "preserved"
    else:
        try:
            with os.fdopen(descriptor, "wb") as output:
                output.write(skeleton)
        except OSError:
            file.unlink(missing_ok=True)
            raise
        state = "created"
    if file.is_symlink() or not file.is_file():
        fail(f"{file.name} must be a regular non-symlink file")
    try:
        message = validate_message(file.read_bytes(), subject_for(tag))
        status = "complete"
    except ValueError as error:
        message = file.read_text(encoding="utf-8", errors="replace")
        status = f"incomplete: {error}"
    print(f"[{'ok' if status == 'complete' else '..'}] {state} {file.name} ({status}):")
    print(message, end="")


def main() -> None:
    args = sys.argv[1:]
    if len(args) in (2, 3) and args[0] == "--validate-message":
        subject = args[2] if len(args) == 3 else None
        validate_message(Path(args[1]).read_bytes(), subject)
    elif not args:
        prepare()
    else:
        fail("expected prepare or validate-message mode")


if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError) as error:
        # Never echo a loader path or raw message-directory path.
        detail = (
            str(error)
            if isinstance(error, ValueError)
            else "unable to prepare external tag message"
        )
        print(f"error: {detail}", file=sys.stderr)
        sys.exit(1)
